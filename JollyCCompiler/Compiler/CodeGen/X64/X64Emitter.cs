// ============================================================================
// JollyCCompiler - X64Emitter
// ============================================================================
//
// PURPOSE
// -------
//
// X64Emitter is responsible for generating the raw x64 machine code used
// by the JollyCCompiler.
//
// The compiler frontend parses C source code and converts it into an
// intermediate representation of operations. The X64Emitter is the part
// of the compiler that converts those operations into actual x64 CPU
// instructions.
//
// For example, a C expression:
//
//     a + b
//
// may eventually result in calls to the emitter such as:
//
//     MovEaxRbpDisp8(...);
//     MovEcxRbpDisp8(...);
//     AddEaxEcx();
//
// which produce machine-code bytes equivalent to:
//
//     mov eax, [rbp-4]
//     mov ecx, [rbp-8]
//     add eax, ecx
//
// The resulting bytes are stored in the internal _code collection and can
// eventually be written to an executable image or other generated code
// buffer.
//
//
// WHAT THE EMITTER DOES
// ---------------------
//
// The emitter performs several related jobs:
//
// 1. MACHINE-CODE GENERATION
//
//    Converts individual x64 instructions into their corresponding opcode
//    bytes.
//
//    Example:
//
//        add eax, ecx
//
//    becomes:
//
//        01 C8
//
//    The emitter stores these bytes in _code.
//
//
// 2. INSTRUCTION TRACKING
//
//    Every emitted instruction is also recorded in _instructions.
//
//    This allows the compiler to retain information about:
//
//        - The byte offset of the instruction
//        - The machine-code bytes
//        - A readable assembly representation
//
//    For example:
//
//        add eax, ecx
//
//    is stored as an X64Instruction alongside its generated bytes.
//
//    This is useful for debugging, diagnostics, disassembly and verifying
//    generated code.
//
//
// 3. LABEL MANAGEMENT
//
//    The emitter can create and mark labels used by conditional and
//    unconditional branches.
//
//    Example:
//
//        loop_start:
//
//            ...
//            jmp loop_start
//
//    Labels do not necessarily have their final machine-code addresses when
//    the instruction is initially emitted. The emitter therefore records
//    labels and creates fixups for instructions whose final displacement
//    cannot yet be known.
//
//
// 4. BRANCH FIXUPS
//
//    Instructions such as:
//
//        jmp
//        je
//        jne
//        jl
//        jle
//        jg
//        jge
//        jb
//        jbe
//        ja
//        jae
//
//    use relative offsets.
//
//    When the branch is emitted, the destination label may not have been
//    defined yet. The emitter therefore writes a placeholder displacement
//    and records an X64Fixup.
//
//    Once all labels are known, the compiler can resolve those fixups and
//    write the correct relative offsets into the generated machine code.
//
//
// 5. RIP-RELATIVE FIXUPS
//
//    The emitter also supports RIP-relative references used for accessing
//    functions and global data.
//
//    For example:
//
//        lea rax, [globalVariable]
//
//    cannot always be encoded with the final displacement immediately
//    available. The emitter therefore records a RIP-relative fixup which
//    can be resolved once the final addresses are known.
//
//
// 6. STACK-FRAME ACCESS
//
//    The emitter provides instructions for accessing local variables through
//    the current function's RBP-based stack frame.
//
//    For example:
//
//        [rbp-4]
//        [rbp-8]
//        [rbp+16]
//
//    are used to access local variables, parameters and other stack-frame
//    data.
//
//    The emitter provides both 8-bit and 32-bit displacement versions of
//    these instructions.
//
//
// 7. FUNCTION CALL SUPPORT
//
//    The emitter generates the instructions required to call functions.
//
//    This includes:
//
//        - Relative calls
//        - Indirect RIP-relative calls
//        - Windows x64 argument registers
//        - Stack arguments
//        - Stack-space calculation
//
//    The Windows x64 integer/pointer argument registers are:
//
//        RCX
//        RDX
//        R8
//        R9
//
//    The emitter contains helper methods that move values into these
//    registers before a function call.
//
//
// 8. INTEGER DATA TYPES
//
//    The emitter supports operations on several integer sizes:
//
//        char       -> 8 bits
//        short      -> 16 bits
//        int        -> 32 bits
//        long       -> 64 bits
//
//    It also contains instructions required for signed and unsigned
//    extension:
//
//        movsx      -> sign extension
//        movzx      -> zero extension
//
//    For example:
//
//        unsigned char -> int
//
//    requires zero extension:
//
//        movzx eax, al
//
//    while:
//
//        signed char -> int
//
//    requires sign extension:
//
//        movsx eax, al
//
//
// 9. FLOAT AND DOUBLE SUPPORT
//
//    Floating-point values are handled using XMM registers.
//
//        float  -> SSE single-precision instructions
//        double -> SSE double-precision instructions
//
//    The compiler currently uses XMM0 as the primary floating-point result
//    register and XMM1/XMM2/XMM3 as additional temporary registers.
//
//    Examples:
//
//        movss
//        movsd
//        addss
//        addsd
//        subss
//        subsd
//        mulss
//        mulsd
//        divss
//        divsd
//
//    are emitted by the corresponding methods in this class.
//
//
// 10. RAW BYTE EMISSION
//
//     EmitByte() and EmitBytes() allow the compiler to append raw machine
//     code bytes directly.
//
//     These are useful when an instruction does not require additional
//     metadata or when low-level code needs to be emitted directly.
//
//
// HOW THE EMITTER WORKS
// ---------------------
//
// Most instruction methods follow the same basic pattern:
//
//     1. Record the current code offset.
//     2. Construct the machine-code bytes.
//     3. Append the bytes to _code.
//     4. Record an X64Instruction describing the generated instruction.
//
// Example:
//
//     public void MovEcxEax()
//     {
//         var offset = Offset;
//         var bytes = new byte[]
//         {
//             0x89,
//             0xC1
//         };
//
//         _code.AddRange(bytes);
//         _instructions.Add(new X64Instruction(
//             offset,
//             bytes,
//             "mov ecx, eax"));
//     }
//
// The important point is that the emitter does not interpret C source code.
// It does not decide what an expression means.
//
// Instead, the compiler's code-generation logic decides what operation is
// required and calls the appropriate emitter method.
//
//
// COMPILER FLOW
// -------------
//
// A simplified view of the compiler is:
//
//     C source
//         |
//         v
//     Lexer
//         |
//         v
//     Parser
//         |
//         v
//     AST / expressions
//         |
//         v
//     Code generation
//         |
//         v
//     X64Emitter
//         |
//         v
//     x64 machine-code bytes
//         |
//         v
//     Generated executable code
//
//
// EXAMPLE
// -------
//
// Given:
//
//     int add(int a, int b)
//     {
//         return a + b;
//     }
//
// The code generator can use the emitter to produce instructions equivalent
// to:
//
//     mov eax, ecx
//     add eax, edx
//     ret
//
// Where:
//
//     ECX = first integer argument
//     EDX = second integer argument
//     EAX = integer return value
//
// The X64Emitter is responsible for converting those individual instructions
// into the correct x64 opcode bytes.
//
//
// IMPORTANT DESIGN PRINCIPLE
// --------------------------
//
// X64Emitter should remain a relatively low-level class.
//
// It should:
//
//     - Generate machine-code bytes.
//     - Track generated instructions.
//     - Track labels.
//     - Record fixups.
//     - Provide small instruction-building helpers.
//
// It should not:
//
//     - Parse C source code.
//     - Perform semantic analysis.
//     - Decide C type rules.
//     - Allocate compiler variables.
//     - Build AST nodes.
//     - Decide high-level control flow.
//
// Those responsibilities belong to other parts of the compiler.
//
//
// ============================================================================
// x64 REGISTER REFERENCE
// ============================================================================
//
// GENERAL PURPOSE REGISTERS
// -------------------------
//
// RAX / EAX / AX / AL
//   RAX = 64-bit register
//   EAX = lower 32 bits of RAX
//   AX  = lower 16 bits of RAX
//   AL  = lower 8 bits of RAX
//   Main integer/result register in this compiler.
//
// RBX / EBX / BX / BL
//   General-purpose register.
//   Available for temporary values.
//
// RCX / ECX / CX / CL
//   General-purpose register.
//   Windows x64: first integer/pointer function argument.
//   Also used as a temporary/second operand in this compiler.
//
// RDX / EDX / DX / DL
//   General-purpose register.
//   Windows x64: second integer/pointer function argument.
//   Also used by integer division.
//
// RSI / ESI / SI / SIL
//   General-purpose register.
//   Historically used as a source-index register.
//
// RDI / EDI / DI / DIL
//   General-purpose register.
//   Historically used as a destination-index register.
//
// RBP / EBP / BP / BPL
//   Stack-frame/base pointer.
//   Used by this compiler to access local variables.
//
// RSP / ESP / SP / SPL
//   Stack pointer.
//   Points to the current top of the stack.
//   Used for stack allocation, function calls and stack arguments.
//
// R8 / R8D / R8W / R8B
//   General-purpose register.
//   Windows x64: third integer/pointer function argument.
//
// R9 / R9D / R9W / R9B
//   General-purpose register.
//   Windows x64: fourth integer/pointer function argument.
//
// R10 / R10D / R10W / R10B
//   General-purpose temporary register.
//
// R11 / R11D / R11W / R11B
//   General-purpose temporary register.
//
// R12 / R12D / R12W / R12B
//   General-purpose register.
//
// R13 / R13D / R13W / R13B
//   General-purpose register.
//
// R14 / R14D / R14W / R14B
//   General-purpose register.
//
// R15 / R15D / R15W / R15B
//   General-purpose register.
//
// ============================================================================

using System.Buffers.Binary;
using System.Diagnostics;

namespace JollyCCompiler.Compiler.CodeGen.X64
{
    public sealed class X64Emitter
    {
        private readonly List<byte> _code = new();
        private readonly List<X64Instruction> _instructions = new();
        private readonly List<X64Fixup> _fixups = new();
        private readonly Dictionary<string, int> _labels = new();

        private int _labelCounter;

        // Returns the current byte offset in the emitted machine code.
        public int Offset => _code.Count;

        // Returns the list of emitted instructions and their descriptions.
        public IReadOnlyList<X64Instruction> Instructions => _instructions;

        // Returns the list of relocations/fixups that still need resolving.
        public IReadOnlyList<X64Fixup> Fixups => _fixups;

        // Returns the labels defined in the emitted code.
        public IReadOnlyDictionary<string, int> Labels => _labels;

        // Returns the complete emitted machine-code buffer.
        public byte[] GetCode()
        {
            var result = _code.ToArray();
            return result;
        }

        // ------------------------------------------------------------
        // 32-bit integer immediate/register operations
        // ------------------------------------------------------------

        // Loads a signed 32-bit immediate value into EAX.
        public void MovEax(int value)
        {
            var offset = Offset;
            Span<byte> buffer = stackalloc byte[4];
            BinaryPrimitives.WriteInt32LittleEndian(buffer, value);

            var bytes = new byte[]
            {
            0xB8,
            buffer[0],
            buffer[1],
            buffer[2],
            buffer[3]
            };

            _code.AddRange(bytes);
            _instructions.Add(new X64Instruction(offset, bytes, $"mov eax, {value}"));
        }

        // Loads an unsigned 32-bit immediate value into EAX.
        public void MovEax(uint value)
        {
            var offset = Offset;

            var bytes = new byte[]
            {
            0xB8,
            (byte)value,
            (byte)(value >> 8),
            (byte)(value >> 16),
            (byte)(value >> 24)
            };

            _code.AddRange(bytes);
            _instructions.Add(new X64Instruction(offset, bytes, $"mov eax, {value}"));
        }

