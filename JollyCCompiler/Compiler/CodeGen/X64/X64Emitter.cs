        // ------------------------------------------------------------
        // Function argument passing
        // ------------------------------------------------------------

        // Moves an integer value in EAX to the appropriate Windows x64
        // integer argument register.
        public void MoveEaxToArgumentRegister(int argumentIndex)
        {
            switch (argumentIndex)
            {
                case 0:
                    MovEcxEax();
                    break;

                case 1:
                    MovEdxEax();
                    break;

                case 2:
                    MovR8dEax();
                    break;

                case 3:
                    MovR9dEax();
                    break;

                default:
                    throw new ArgumentOutOfRangeException(nameof(argumentIndex));
            }
        }

        // Moves a 64-bit value in RAX to the appropriate Windows x64
        // integer argument register.
        public void MoveRaxToArgumentRegister(int argumentIndex)
        {
            switch (argumentIndex)
            {
                case 0:
                    MovRcxRax();
                    break;

                case 1:
                    MovRdxRax();
                    break;

                case 2:
                    MovR8Rax();
                    break;

                case 3:
                    MovR9Rax();
                    break;

                default:
                    throw new ArgumentOutOfRangeException(nameof(argumentIndex));
            }
        }

        // Stores a 32-bit argument into its Windows x64 stack slot.
        public void MoveEaxToStackArgument(int argumentIndex)
        {
            if (argumentIndex < 4)
            {
                throw new ArgumentOutOfRangeException(nameof(argumentIndex));
            }

            var displacement = 32 + ((argumentIndex - 4) * 8);
            MovRspDisp32Eax(displacement);
        }

        // Stores a 64-bit argument into its Windows x64 stack slot.
        public void MoveRaxToStackArgument(int argumentIndex)
        {
            if (argumentIndex < 4)
            {
                throw new ArgumentOutOfRangeException(nameof(argumentIndex));
            }

            var displacement = 32 + ((argumentIndex - 4) * 8);
            MovRspDisp32Rax(displacement);
        }

        // Calculates the required Windows x64 call stack size,
        // including shadow space and stack arguments.
        public int GetCallStackSize(int argumentCount)
        {
            var stackArguments = Math.Max(0, argumentCount - 4);
            var required = 32 + (stackArguments * 8);

            return (required + 15) & ~15;
        }


