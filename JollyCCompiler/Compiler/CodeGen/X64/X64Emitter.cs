    // ============================================================================
    // x64 REGISTER REFERENCE
    // ============================================================================
    //
    // GENERAL PURPOSE REGISTERS
    // -------------------------
    //
    // RAX / EAX / AX / AL
    //   RAX = 64-bit register
    //   EAX = lower 32 bits of RAX
    //   AX  = lower 16 bits of RAX
    //   AL  = lower 8 bits of RAX
    //   Main integer/result register in this compiler.
    //
    // RBX / EBX / BX / BL
    //   General-purpose register.
    //   Available for temporary values.
    //
    // RCX / ECX / CX / CL
    //   General-purpose register.
    //   Windows x64: first integer/pointer function argument.
    //   Also used as a temporary/second operand in this compiler.
    //
    // RDX / EDX / DX / DL
    //   General-purpose register.
    //   Windows x64: second integer/pointer function argument.
    //   Also used by integer division.
    //
    // RSI / ESI / SI / SIL
    //   General-purpose register.
    //   Historically used as a source-index register.
    //
    // RDI / EDI / DI / DIL
    //   General-purpose register.
    //   Historically used as a destination-index register.
    //
    // RBP / EBP / BP / BPL
    //   Stack-frame/base pointer.
    //   Used by this compiler to access local variables.
    //
    // RSP / ESP / SP / SPL
    //   Stack pointer.
    //   Points to the current top of the stack.
    //   Used for stack allocation, function calls and stack arguments.
    //
    // R8 / R8D / R8W / R8B
    //   General-purpose register.
    //   Windows x64: third integer/pointer function argument.
    //
    // R9 / R9D / R9W / R9B
    //   General-purpose register.
    //   Windows x64: fourth integer/pointer function argument.
    //
    // R10 / R10D / R10W / R10B
    //   General-purpose temporary register.
    //
    // R11 / R11D / R11W / R11B
    //   General-purpose temporary register.
    //
    // R12 / R12D / R12W / R12B
    //   General-purpose register.
    //
    // R13 / R13D / R13W / R13B
    //   General-purpose register.
    //
    // R14 / R14D / R14W / R14B
    //   General-purpose register.
    //
    // R15 / R15D / R15W / R15B
    //   General-purpose register.
    //
    //
    // REGISTER SIZES
    // --------------
    //
    // RAX = 64 bits
    // EAX = 32 bits
    //  AX = 16 bits
    //  AL =  8 bits
    //
    // Writing to a 32-bit register such as EAX clears the upper 32 bits
    // of the corresponding 64-bit register.
    //
    // Example:
    //
    //     mov eax, 123
    //
    // Results in:
    //
    //     RAX = 000000000000007B
    //     EAX =         0000007B
    //
    //
    // INTEGER REGISTER CONVENTION USED BY THIS COMPILER
    // --------------------------------------------------
    //
    // EAX / RAX
    //   Primary integer expression result.
    //
    // ECX / RCX
    //   Temporary integer operand.
    //   Also first Windows x64 integer/pointer argument.
    //
    // EDX / RDX
    //   Temporary integer operand.
    //   Also second Windows x64 integer/pointer argument.
    //   Used as the high half of the dividend by 32/64-bit division.
    //
    // R8D / R8
    //   Third Windows x64 integer/pointer argument.
    //
    // R9D / R9
    //   Fourth Windows x64 integer/pointer argument.
    //
    // RBP
    //   Base of the current function stack frame.
    //
    // RSP
    //   Current stack pointer.
    //
    //
    // 8-BIT AND 16-BIT VALUES
    // ------------------------
    //
    // AL
    //   8-bit value.
    //   Used for char / unsigned char operations.
    //
    // AX
    //   16-bit value.
    //   Used for short / unsigned short operations.
    //
    // For signed values, sign extension is required:
    //
    //     movsx eax, al     // signed char -> int
    //     movsx eax, ax     // signed short -> int
    //
    // For unsigned values, zero extension is required:
    //
    //     movzx eax, al     // unsigned char -> int
    //     movzx eax, ax     // unsigned short -> int
    //
    //
    // FLOATING-POINT REGISTERS
    // ------------------------
    //
    // XMM0
    //   Main floating-point expression result.
    //   Used for float and double results.
    //
    // XMM1
    //   Secondary floating-point operand/temp.
    //
    // XMM2
    //   Additional floating-point temporary.
    //
    // XMM3
    //   Additional floating-point temporary.
    //
    // movss
    //   32-bit single-precision float operation.
    //
    // movsd
    //   64-bit double-precision operation.
    //
    //
    // FLOATING-POINT CONVENTION USED BY THIS COMPILER
    // -----------------------------------------------
    //
    // XMM0
    //   Primary float/double expression result.
    //
    // XMM1
    //   Secondary float/double operand.
    //
    // XMM2 / XMM3
    //   Additional temporary floating-point registers.
    //
    //
    // WINDOWS x64 FUNCTION ARGUMENT REGISTERS
    // ---------------------------------------
    //
    // Integer / pointer arguments:
    //
    //     Argument 1 -> RCX
    //     Argument 2 -> RDX
    //     Argument 3 -> R8
    //     Argument 4 -> R9
    //
    // Floating-point arguments use the corresponding XMM registers according
    // to the Windows x64 calling convention.
    //
    //
    // STACK FRAME
    // ----------
    //
    // Typical function prologue:
    //
    //     push rbp
    //     mov  rbp, rsp
    //
    // Local variables are accessed relative to RBP:
    //
    //     [rbp-4]     32-bit local
    //     [rbp-8]     64-bit local
    //     [rbp-2]     16-bit local
    //     [rbp-1]      8-bit local
    //
    // Typical function epilogue:
    //
    //     pop rbp
    //     ret
    //
    //
    // STACK
    // -----
    //
    // RSP points to the current top of the stack.
    //
    //     push rax
    //         Decreases RSP and stores RAX.
    //
    //     pop rax
    //         Loads RAX and increases RSP.
    //
    // Stack memory is also used for function arguments beyond the first
    // four integer/pointer arguments.
    //
    //
    // IMPORTANT REGISTER RELATIONSHIPS
    // --------------------------------
    //
    // RAX
    //  ├── EAX   (lower 32 bits)
    //  │    └── AX   (lower 16 bits)
    //  │         └── AL   (lower 8 bits)
    //
    // RCX
    //  ├── ECX
    //  │    └── CX
    //  │         └── CL
    //
    // RDX
    //  ├── EDX
    //  │    └── DX
    //  │         └── DL
    //
    // RBX
    //  ├── EBX
    //  │    └── BX
    //  │         └── BL
    //
    // RBP
    //  ├── EBP
    //  │    └── BP
    //  │         └── BPL
    //
    // RSP
    //  ├── ESP
    //  │    └── SP
    //  │         └── SPL
    //
    // R8
    //  └── R8D -> R8W -> R8B
    //
    // R9
    //  └── R9D -> R9W -> R9B
    //
    // R10
    //  └── R10D -> R10W -> R10B
    //
    // R11
    //  └── R11D -> R11W -> R11B
    //
    // R12
    //  └── R12D -> R12W -> R12B
    //
    // R13
    //  └── R13D -> R13W -> R13B
    //
    // R14
    //  └── R14D -> R14W -> R14B
    //
    // R15
    //  └── R15D -> R15W -> R15B
    //
    // ============================================================================

