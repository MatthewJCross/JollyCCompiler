            {
                throw new ArgumentOutOfRangeException(nameof(value));
            }

            var offset = Offset;

            if (value <= 127)
            {
                var bytes = new byte[]
                {
                0x48,
                0x83,
                0xEC,
                (byte)value
                };

                _code.AddRange(bytes);
                _instructions.Add(new X64Instruction(offset, bytes, $"sub rsp, {value}"));
                return;
